def _download(url: str, path: Path) -> Path:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not path.exists():
        print("Downloading", url)
        urllib.request.urlretrieve(url, path)
    return path


def _subsample(X: np.ndarray, y: np.ndarray, n: Optional[int], seed: int) -> Tuple[np.ndarray, np.ndarray]:
    if n is None or len(y) <= n:
        return X, y
    idx, _ = train_test_split(np.arange(len(y)), train_size=n, random_state=seed, stratify=y)
    return X[idx], y[idx]


def _fit_tabular_preprocessor(train_df: pd.DataFrame, val_df: pd.DataFrame, test_df: pd.DataFrame,
                              target: str, drop_cols: Sequence[str]) -> Tuple[np.ndarray, np.ndarray, np.ndarray, List[str]]:
    features = [c for c in train_df.columns if c != target and c not in set(drop_cols)]
    Xtr, Xv, Xte = train_df[features].copy(), val_df[features].copy(), test_df[features].copy()
    cat = [c for c in features if Xtr[c].dtype == "object" or str(Xtr[c].dtype).startswith("category")]
    num = [c for c in features if c not in cat]
    pre = ColumnTransformer([
        ("num", Pipeline([("impute", SimpleImputer(strategy="median")), ("scale", StandardScaler())]), num),
        ("cat", Pipeline([("impute", SimpleImputer(strategy="most_frequent")),
                          ("onehot", OneHotEncoder(handle_unknown="ignore", sparse_output=False))]), cat),
    ], remainder="drop")
    Xtr_a = pre.fit_transform(Xtr).astype(np.float32)
    Xv_a = pre.transform(Xv).astype(np.float32)
    Xte_a = pre.transform(Xte).astype(np.float32)
    try:
        names = list(pre.get_feature_names_out())
    except Exception:
        names = [f"f{i}" for i in range(Xtr_a.shape[1])]
    return Xtr_a, Xv_a, Xte_a, names


def load_nsl_kdd(seed: int = 42) -> DataBundle:
    cache = ROOT / "data" / "nsl_kdd"
    tr_path = _download("https://raw.githubusercontent.com/defcom17/NSL_KDD/master/KDDTrain+.txt", cache / "KDDTrain+.txt")
    te_path = _download("https://raw.githubusercontent.com/defcom17/NSL_KDD/master/KDDTest+.txt", cache / "KDDTest+.txt")
    tr = pd.read_csv(tr_path, names=NSL_COLUMNS)
    te = pd.read_csv(te_path, names=NSL_COLUMNS)
    tr["label"] = (tr["label"].astype(str).str.strip() != "normal").astype(np.float32)
    te["label"] = (te["label"].astype(str).str.strip() != "normal").astype(np.float32)
    train_df, val_df = train_test_split(tr, test_size=0.20, random_state=seed, stratify=tr["label"])
    Xtr, Xv, Xte, names = _fit_tabular_preprocessor(train_df, val_df, te, "label", ["difficulty"])
    ytr, yv, yte = train_df.label.to_numpy(np.float32), val_df.label.to_numpy(np.float32), te.label.to_numpy(np.float32)
    Xtr, ytr = _subsample(Xtr, ytr, CFG.max_train_rows, seed)
    Xte, yte = _subsample(Xte, yte, CFG.max_test_rows, seed)
    tr_hash = set(pd.util.hash_pandas_object(tr.drop(columns=["difficulty"]), index=False).astype(str))
    te_hash = set(pd.util.hash_pandas_object(te.drop(columns=["difficulty"]), index=False).astype(str))
    audit = {
        "train_rows": len(train_df), "val_rows": len(val_df), "test_rows": len(te),
        "raw_train_exact_duplicates": int(tr.duplicated().sum()),
        "raw_test_exact_duplicates": int(te.duplicated().sum()),
        "train_test_exact_overlap_hashes": int(len(tr_hash.intersection(te_hash))),
        "train_prevalence": float(ytr.mean()), "val_prevalence": float(yv.mean()), "test_prevalence": float(yte.mean()),
    }
    return DataBundle("NSL_KDD", Xtr, ytr, Xv, yv, Xte, yte, names, audit)


def _load_generic_train_test(train_csv: str, test_csv: str, name: str, seed: int,
                             target_candidates=("label", "Label"), drop_cols=()) -> DataBundle:
    tr, te = pd.read_csv(train_csv, low_memory=False), pd.read_csv(test_csv, low_memory=False)
    target = next((c for c in target_candidates if c in tr.columns), None)
    if target is None:
        raise ValueError(f"No target column found in {name}; tried {target_candidates}")
    tr[target] = pd.to_numeric(tr[target], errors="coerce")
    te[target] = pd.to_numeric(te[target], errors="coerce")
    tr, te = tr.dropna(subset=[target]).copy(), te.dropna(subset=[target]).copy()
    tr[target], te[target] = (tr[target] != 0).astype(np.float32), (te[target] != 0).astype(np.float32)
    train_df, val_df = train_test_split(tr, test_size=.20, random_state=seed, stratify=tr[target])
    Xtr, Xv, Xte, names = _fit_tabular_preprocessor(train_df, val_df, te, target, drop_cols)
    ytr, yv, yte = train_df[target].to_numpy(np.float32), val_df[target].to_numpy(np.float32), te[target].to_numpy(np.float32)
    Xtr, ytr = _subsample(Xtr, ytr, CFG.max_train_rows, seed)
    Xte, yte = _subsample(Xte, yte, CFG.max_test_rows, seed)
    audit = {"train_rows": len(tr), "test_rows": len(te), "train_duplicates": int(tr.duplicated().sum()),
             "test_duplicates": int(te.duplicated().sum()), "train_prevalence": float(ytr.mean()),
             "val_prevalence": float(yv.mean()), "test_prevalence": float(yte.mean())}
    return DataBundle(name, Xtr, ytr, Xv, yv, Xte, yte, names, audit)



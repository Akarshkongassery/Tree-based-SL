# %%% EXPERIMENT E5: Pareto front and deployment preference profiles
def pareto_mask(df: pd.DataFrame) -> np.ndarray:
    # Maximise F1/recall; minimise communication/client compute/latency.
    vals = np.column_stack([-df.val_f1, -df.val_recall, df.communication_mb_batch,
                            df.client_mflops_batch, df.estimated_total_latency_ms])
    keep = np.ones(len(df), dtype=bool)
    for i in range(len(df)):
        for j in range(len(df)):
            if i != j and np.all(vals[j] <= vals[i]) and np.any(vals[j] < vals[i]):
                keep[i] = False; break
    return keep



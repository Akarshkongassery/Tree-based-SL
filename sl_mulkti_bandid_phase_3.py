def file_sha256(path: str | Path) -> str:
    h = hashlib.sha256()
    with open(path, "rb") as f:
        for chunk in iter(lambda: f.read(1024 * 1024), b""):
            h.update(chunk)
    return h.hexdigest()


def summarize_numeric(df: pd.DataFrame, group_cols: Sequence[str], value_cols: Sequence[str]) -> pd.DataFrame:
    rows: List[Dict[str, Any]] = []
    for keys, g in df.groupby(list(group_cols), dropna=False):
        keys = keys if isinstance(keys, tuple) else (keys,)
        row = dict(zip(group_cols, keys))
        for col in value_cols:
            x = pd.to_numeric(g[col], errors="coerce").dropna().to_numpy(float)
            if len(x) == 0:
                continue
            mean = float(np.mean(x))
            sd = float(np.std(x, ddof=1)) if len(x) > 1 else 0.0
            ci = 1.96 * sd / math.sqrt(len(x)) if len(x) > 1 else 0.0
            row.update({f"{col}_mean": mean, f"{col}_sd": sd, f"{col}_ci95": ci, f"{col}_n": len(x)})
        rows.append(row)
    return pd.DataFrame(rows)



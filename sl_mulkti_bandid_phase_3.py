# %% SETUP 5: Modular backbones with 10/20/40 eligible cuts
class ResidualMLPBlock(nn.Module):
    def __init__(self, width: int):
        super().__init__()
        self.net = nn.Sequential(nn.Linear(width, width), nn.ReLU(), nn.Linear(width, width))
        self.act = nn.ReLU()

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.act(x + self.net(x))


class SplitBackbone(nn.Module):
    def __init__(self, input_dim: int, architecture: str, n_cuts: int):
        super().__init__()
        width = 128
        blocks: List[nn.Module] = [nn.Sequential(nn.Linear(input_dim, width), nn.ReLU())]
        if architecture == "deep_mlp":
            for i in range(1, n_cuts):
                next_width = max(24, width - (8 if i % 3 == 0 else 0))
                blocks.append(nn.Sequential(nn.Linear(width, next_width), nn.ReLU()))
                width = next_width
        elif architecture == "residual_mlp":
            blocks.extend(ResidualMLPBlock(width) for _ in range(n_cuts - 1))
        else:
            raise ValueError("architecture must be deep_mlp or residual_mlp")
        self.blocks = nn.ModuleList(blocks)
        self.classifier = nn.Linear(width, 1)

    @property
    def n_cuts(self) -> int:
        return len(self.blocks)

    def forward_until(self, x: torch.Tensor, cut: int) -> torch.Tensor:
        for block in self.blocks[:cut]:
            x = block(x)
        return x

    def forward_from(self, z: torch.Tensor, cut: int) -> torch.Tensor:
        for block in self.blocks[cut:]:
            z = block(z)
        return self.classifier(z).squeeze(-1)

    def forward(self, x: torch.Tensor) -> torch.Tensor:
        return self.forward_from(self.forward_until(x, self.n_cuts), self.n_cuts)


def build_model(input_dim: int, architecture: str, n_cuts: int, seed: int) -> SplitBackbone:
    set_seed(seed)
    return SplitBackbone(input_dim, architecture, n_cuts)


def split_forward(model: SplitBackbone, x: torch.Tensor, cut: int) -> torch.Tensor:
    z = model.forward_until(x, cut)
    # z is the smashed activation.  Autograd across this boundary reproduces
    # the same gradient as explicit gradient send/receive in one process.
    return model.forward_from(z, cut)


def tensor_loaders(data: DataBundle, seed: int) -> Tuple[DataLoader, DataLoader, DataLoader]:
    g = torch.Generator().manual_seed(seed)
    def ds(X, y): return TensorDataset(torch.tensor(X), torch.tensor(y))
    tr = DataLoader(ds(data.X_train, data.y_train), batch_size=CFG.train_batch_size, shuffle=True,
                    generator=g, num_workers=CFG.num_workers)
    va = DataLoader(ds(data.X_val, data.y_val), batch_size=CFG.eval_batch_size, shuffle=False)
    te = DataLoader(ds(data.X_test, data.y_test), batch_size=CFG.eval_batch_size, shuffle=False)
    return tr, va, te


# %% SETUP 6: Training, metrics, profiling, reward and cache
def binary_metrics(y: np.ndarray, prob: np.ndarray) -> Dict[str, float]:
    pred = (prob >= 0.5).astype(int)
    out = {
        "accuracy": accuracy_score(y, pred),
        "precision": precision_score(y, pred, zero_division=0),
        "recall": recall_score(y, pred, zero_division=0),
        "f1": f1_score(y, pred, zero_division=0),
        "pr_auc": average_precision_score(y, prob),
    }
    out["roc_auc"] = roc_auc_score(y, prob) if len(np.unique(y)) > 1 else float("nan")
    return {k: float(v) for k, v in out.items()}


@torch.no_grad()
def evaluate(model: SplitBackbone, loader: DataLoader, cut: int) -> Dict[str, float]:
    model.eval()
    ys, ps = [], []
    for xb, yb in loader:
        logits = split_forward(model, xb.to(DEVICE), cut)
        ys.append(yb.numpy())
        ps.append(torch.sigmoid(logits).cpu().numpy())
    return binary_metrics(np.concatenate(ys), np.concatenate(ps))


def train_candidate(data: DataBundle, architecture: str, n_cuts: int, cut: int, seed: int,
                    epochs: Optional[int] = None, initial_state: Optional[Mapping[str, torch.Tensor]] = None,
                    return_state: bool = False) -> Dict[str, Any]:
    epochs = CFG.epochs_per_candidate if epochs is None else epochs
    model = build_model(data.X_train.shape[1], architecture, n_cuts, seed).to(DEVICE)
    if initial_state is not None:
        model.load_state_dict(initial_state)
    tr, va, te = tensor_loaders(data, seed)
    opt = torch.optim.Adam(model.parameters(), lr=CFG.learning_rate)
    loss_fn = nn.BCEWithLogitsLoss()
    start = time.perf_counter()
    model.train()
    for _ in range(epochs):
        for xb, yb in tr:
            xb, yb = xb.to(DEVICE), yb.to(DEVICE)
            opt.zero_grad(set_to_none=True)
            loss = loss_fn(split_forward(model, xb, cut), yb)
            loss.backward()
            opt.step()
    train_seconds = time.perf_counter() - start
    val = evaluate(model, va, cut)
    result: Dict[str, Any] = {"cut": cut, "seed": seed, "epochs": epochs, "train_seconds": train_seconds,
                              **{f"val_{k}": v for k, v in val.items()}}
    if return_state:
        result["state_dict"] = {k: v.detach().cpu().clone() for k, v in model.state_dict().items()}
        result["test_metrics"] = evaluate(model, te, cut)
    return result


def count_params(modules: Iterable[nn.Module]) -> int:
    return sum(p.numel() for m in modules for p in m.parameters())


def profile_model(model: SplitBackbone, batch_size: int, repeats: Optional[int] = None) -> pd.DataFrame:
    repeats = CFG.latency_repeats if repeats is None else repeats
    x = torch.zeros(batch_size, next(model.parameters()).shape[1] if isinstance(model.blocks[0][0], nn.Linear) else 1,
                    device=DEVICE)
    total_params = sum(p.numel() for p in model.parameters())
    rows = []
    for cut in range(1, model.n_cuts + 1):
        with torch.no_grad():
            z = model.forward_until(x, cut)
        activation_elements = int(z[0].numel())
        comm_bytes = 2 * batch_size * activation_elements * CFG.fp_bytes
        client_params = count_params(model.blocks[:cut])
        server_params = total_params - client_params
        # Approximate dense FLOPs as 2*number of weights, per sample.
        client_weights = sum(p.numel() for m in model.blocks[:cut] for n, p in m.named_parameters() if "weight" in n)
        server_weights = sum(p.numel() for m in list(model.blocks[cut:]) + [model.classifier]
                             for n, p in m.named_parameters() if "weight" in n)
        client_flops_sample, server_flops_sample = 2 * client_weights, 2 * server_weights
        # Peak edge footprint approximation: parameters + gradients + Adam states + activation.
        client_memory = (4 * client_params * CFG.fp_bytes + batch_size * activation_elements * CFG.fp_bytes)
        times = []
        model.eval()
        for _ in range(CFG.latency_warmups):
            with torch.no_grad(): split_forward(model, x, cut)
        if DEVICE.type == "cuda": torch.cuda.synchronize()
        for _ in range(repeats):
            t0 = time.perf_counter()
            with torch.no_grad(): split_forward(model, x, cut)
            if DEVICE.type == "cuda": torch.cuda.synchronize()
            times.append((time.perf_counter() - t0) * 1000)
        rows.append({
            "cut": cut, "activation_elements_per_sample": activation_elements,
            "communication_bytes_batch": comm_bytes, "communication_mb_batch": comm_bytes / 1e6,
            "client_flops_sample": client_flops_sample, "server_flops_sample": server_flops_sample,
            "client_mflops_batch": client_flops_sample * batch_size / 1e6,
            "server_mflops_batch": server_flops_sample * batch_size / 1e6,
            "client_params": client_params, "server_params": server_params,
            "client_memory_mb": client_memory / 1e6,
            "local_compute_latency_ms": float(np.median(times)),
            "local_compute_latency_p95_ms": float(np.percentile(times, 95)),
        })
    return pd.DataFrame(rows)


def add_context_costs(df: pd.DataFrame, bandwidth_mbps: float, client_gflops: float,
                      server_gflops: float) -> pd.DataFrame:
    d = df.copy()
    d["bandwidth_mbps"] = bandwidth_mbps
    d["client_gflops"] = client_gflops
    d["server_gflops"] = server_gflops
    d["communication_latency_ms"] = d.communication_bytes_batch * 8 / (bandwidth_mbps * 1e6) * 1000
    d["estimated_client_latency_ms"] = d.client_mflops_batch / (client_gflops * 1000) * 1000
    d["estimated_server_latency_ms"] = d.server_mflops_batch / (server_gflops * 1000) * 1000
    d["estimated_total_latency_ms"] = (d.communication_latency_ms + d.estimated_client_latency_ms +
                                        d.estimated_server_latency_ms)
    return d


def apply_rast(df: pd.DataFrame) -> pd.DataFrame:
    mask = np.ones(len(df), dtype=bool)
    if CFG.max_comm_mb_per_batch is not None: mask &= df.communication_mb_batch <= CFG.max_comm_mb_per_batch
    if CFG.max_client_mflops_per_batch is not None: mask &= df.client_mflops_batch <= CFG.max_client_mflops_per_batch
    if CFG.max_client_memory_mb is not None: mask &= df.client_memory_mb <= CFG.max_client_memory_mb
    if CFG.max_latency_ms is not None: mask &= df.estimated_total_latency_ms <= CFG.max_latency_ms
    out = df.copy()
    out["feasible"] = mask
    return out


DEPLOYMENT_PROFILES = {
    "balanced": {"f1": .55, "recall": .15, "comm": .15, "client": .05, "latency": .10},
    "security_critical": {"f1": .45, "recall": .40, "comm": .05, "client": .03, "latency": .07},
    "bandwidth_limited": {"f1": .35, "recall": .20, "comm": .30, "client": .05, "latency": .10},
    "compute_limited": {"f1": .35, "recall": .20, "comm": .05, "client": .30, "latency": .10},
}


def add_reward(df: pd.DataFrame, profile: str = "balanced") -> pd.DataFrame:
    d = df.copy()
    w = DEPLOYMENT_PROFILES[profile]
    # Candidate-independent, budget-normalised costs.
    comm_budget = CFG.max_comm_mb_per_batch or max(float(d.communication_mb_batch.max()), 1e-9)
    comp_budget = CFG.max_client_mflops_per_batch or max(float(d.client_mflops_batch.max()), 1e-9)
    lat_budget = CFG.max_latency_ms or max(float(d.estimated_total_latency_ms.max()), 1e-9)
    d["norm_comm"] = (d.communication_mb_batch / comm_budget).clip(lower=0)
    d["norm_client"] = (d.client_mflops_batch / comp_budget).clip(lower=0)
    d["norm_latency"] = (d.estimated_total_latency_ms / lat_budget).clip(lower=0)
    d["reward"] = (w["f1"] * d.val_f1 + w["recall"] * d.val_recall - w["comm"] * d.norm_comm
                   - w["client"] * d.norm_client - w["latency"] * d.norm_latency)
    best_f1, best_rec = float(d.val_f1.max()), float(d.val_recall.max())
    d["detection_acceptable"] = ((d.val_f1 >= CFG.min_f1_ratio_to_best * best_f1) &
                                  (d.val_recall >= CFG.min_recall_ratio_to_best * best_rec))
    d["eligible"] = d.feasible & d.detection_acceptable
    return d


def oracle_path(dataset: str, architecture: str, n_cuts: int, seed: int, epochs: int) -> Path:
    return exp_dir("shared_oracle") / f"{dataset}_{architecture}_K{n_cuts}_seed{seed}_ep{epochs}.csv"


def create_or_load_oracle(data: DataBundle, architecture: str, n_cuts: int, seed: int,
                          epochs: Optional[int] = None, force: bool = False) -> pd.DataFrame:
    epochs = CFG.epochs_per_candidate if epochs is None else epochs
    path = oracle_path(data.name, architecture, n_cuts, seed, epochs)
    if path.exists() and not force:
        return pd.read_csv(path)
    set_seed(seed)
    initial = build_model(data.X_train.shape[1], architecture, n_cuts, seed)
    initial_state = copy.deepcopy(initial.state_dict())
    profile_start = time.perf_counter()
    profiles = profile_model(initial.to(DEVICE), CFG.train_batch_size)
    profiling_seconds = time.perf_counter() - profile_start
    profiles = add_context_costs(profiles, CFG.default_bandwidth_mbps, CFG.default_client_gflops,
                                 CFG.default_server_gflops)
    rows = []
    for cut in range(1, n_cuts + 1):
        print(f"Oracle evaluation: {architecture}, K={n_cuts}, seed={seed}, S{cut}")
        rows.append(train_candidate(data, architecture, n_cuts, cut, seed, epochs, initial_state))
    result = profiles.merge(pd.DataFrame(rows), on="cut", validate="one_to_one")
    result["profiling_seconds_total"] = profiling_seconds
    result = add_reward(apply_rast(result))
    result.to_csv(path, index=False)
    return result


# %% SETUP 7: Search algorithms (faithful to uploaded standard-UCB code)
def run_search(oracle: pd.DataFrame, method: str, rounds: int, seed: int,
               feasible_only: bool = True) -> pd.DataFrame:
    rng = np.random.default_rng(seed)
    pool = oracle[oracle.eligible].copy() if feasible_only else oracle.copy()
    if pool.empty:
        pool = oracle.copy()
    cuts = pool.cut.astype(int).tolist()
    reward_map = dict(zip(pool.cut.astype(int), pool.reward.astype(float)))
    optimum = max(reward_map.values())
    history, seen, counts, means = [], set(), {c: 0 for c in cuts}, {c: 0.0 for c in cuts}
    for t in range(1, rounds + 1):
        if method in ("daucb", "rast_daucb"):
            unseen = [c for c in cuts if counts[c] == 0]
            if unseen:
                cut = unseen[0]  # Standard UCB necessarily evaluates every arm.
            else:
                cut = max(cuts, key=lambda c: means[c] + CFG.ucb_exploration_c * math.sqrt(math.log(t) / counts[c]))
        elif method in ("random", "rast_random"):
            cut = int(rng.choice(cuts))
        elif method == "analytical_latency":
            cut = int(pool.loc[pool.estimated_total_latency_ms.idxmin(), "cut"])
        elif method == "exhaustive":
            cut = cuts[(t - 1) % len(cuts)]
        else:
            raise ValueError(method)
        reward = reward_map[cut]
        counts[cut] += 1
        means[cut] += (reward - means[cut]) / counts[cut]
        seen.add(cut)
        row = pool.loc[pool.cut == cut].iloc[0]
        best = max(reward_map[c] for c in seen)
        history.append({"method": method, "seed": seed, "round": t, "cut": cut, "reward": reward,
                        "best_reward": best, "simple_regret": optimum - best,
                        "unique_cuts": len(seen), "optimal_hit": int(np.isclose(best, optimum))})
    return pd.DataFrame(history)



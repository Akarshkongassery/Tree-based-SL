@torch.no_grad()
def _collect_smashed(model: SplitBackbone, X: np.ndarray, y: np.ndarray, cut: int,
                     batch_size: int = 2048) -> Tuple[np.ndarray, np.ndarray, np.ndarray]:
    model.eval(); zs, xs, ys = [], [], []
    loader = DataLoader(TensorDataset(torch.tensor(X), torch.tensor(y)), batch_size=batch_size, shuffle=False)
    for xb, yb in loader:
        z = model.forward_until(xb.to(DEVICE), cut)
        zs.append(z.cpu().numpy()); xs.append(xb.numpy()); ys.append(yb.numpy())
    return np.concatenate(zs), np.concatenate(xs), np.concatenate(ys)


def _privacy_attack_for_cut(model: SplitBackbone, data: DataBundle, cut: int, seed: int) -> Dict[str, Any]:
    """Honest black-box leakage audit; this is an attack evaluation, not a PET."""
    rng = np.random.default_rng(seed)
    n = min(CFG.privacy_attack_train_rows, len(data.y_train))
    idx = rng.choice(len(data.y_train), n, replace=False)
    ztr, xtr, ytr = _collect_smashed(model, data.X_train[idx], data.y_train[idx], cut)
    zv, xv, yv = _collect_smashed(model, data.X_val, data.y_val, cut)
    z_dim, x_dim = ztr.shape[1], xtr.shape[1]

    decoder = nn.Sequential(nn.Linear(z_dim, 128), nn.ReLU(), nn.Linear(128, x_dim)).to(DEVICE)
    label_attacker = nn.Sequential(nn.Linear(z_dim, 64), nn.ReLU(), nn.Linear(64, 1)).to(DEVICE)
    dec_opt = torch.optim.Adam(decoder.parameters(), lr=1e-3)
    lab_opt = torch.optim.Adam(label_attacker.parameters(), lr=1e-3)
    zt, xt, yt = torch.tensor(ztr), torch.tensor(xtr), torch.tensor(ytr).view(-1, 1)
    loader = DataLoader(TensorDataset(zt, xt, yt), batch_size=512, shuffle=True)
    for _ in range(CFG.privacy_attack_epochs):
        decoder.train(); label_attacker.train()
        for zb, xb, yb in loader:
            zb, xb, yb = zb.to(DEVICE), xb.to(DEVICE), yb.to(DEVICE)
            dec_opt.zero_grad(set_to_none=True)
            torch.mean((decoder(zb) - xb) ** 2).backward(); dec_opt.step()
            lab_opt.zero_grad(set_to_none=True)
            nn.functional.binary_cross_entropy_with_logits(label_attacker(zb), yb).backward(); lab_opt.step()
    decoder.eval(); label_attacker.eval()
    with torch.no_grad():
        recon = decoder(torch.tensor(zv, device=DEVICE)).cpu().numpy()
        label_prob = torch.sigmoid(label_attacker(torch.tensor(zv, device=DEVICE))).cpu().numpy().ravel()
    mse = float(np.mean((recon - xv) ** 2))
    variance = float(np.mean((xv - xv.mean(axis=0, keepdims=True)) ** 2))
    reconstruction_r2 = 1.0 - mse / max(variance, 1e-12)
    return {
        "cut": cut, "seed": seed, "activation_dim": z_dim,
        "reconstruction_mse_standardised": mse,
        "reconstruction_r2": float(reconstruction_r2),
        "label_inference_auc": float(roc_auc_score(yv, label_prob)),
        "label_inference_f1": float(f1_score(yv, label_prob >= 0.5, zero_division=0)),
        "attack_train_rows": n, "attack_epochs": CFG.privacy_attack_epochs,
    }


def run_activation_leakage_audit(data: DataBundle, n_cuts: int = 6,
                                 seeds: Optional[Sequence[int]] = None) -> pd.DataFrame:
    seeds = CFG.generalisation_seeds if seeds is None else tuple(seeds)
    rows = []
    for seed in seeds:
        trained = train_candidate(data, "deep_mlp", n_cuts, n_cuts, seed,
                                  epochs=CFG.final_epochs, return_state=True)
        model = build_model(data.X_train.shape[1], "deep_mlp", n_cuts, seed).to(DEVICE)
        model.load_state_dict(trained["state_dict"])
        for cut in range(1, n_cuts + 1):
            print(f"E8 leakage attack: seed={seed}, cut={cut}/{n_cuts}")
            rows.append(_privacy_attack_for_cut(model, data, cut, seed))
    return pd.DataFrame(rows)


def audit_csv(path: str, label_candidates=("label", "Label", "attack", "class"),
              group_candidates=("Flow ID", "flow_id", "src_ip", "Source IP", "device", "type")) -> Dict[str, Any]:
    df = pd.read_csv(path, low_memory=False)
    label = next((c for c in label_candidates if c in df.columns), None)
    identifiers = [c for c in df.columns if c.lower() in IDENTIFIER_PATTERNS or
                   any(token in c.lower() for token in ("flow id", "src ip", "dst ip", "timestamp"))]
    report: Dict[str, Any] = {
        "path": path, "sha256": file_sha256(path), "rows": len(df), "columns": len(df.columns),
        "exact_duplicate_rows": int(df.duplicated().sum()), "label_column": label,
        "identifier_like_columns": identifiers,
    }
    if label:
        report["label_distribution"] = df[label].astype(str).value_counts(dropna=False).head(50).to_dict()
        feature_cols = [c for c in df.columns if c != label]
        duplicate_features = df.duplicated(feature_cols, keep=False)
        mixed = 0
        if duplicate_features.any():
            mixed = int(df.loc[duplicate_features].groupby(feature_cols, dropna=False)[label].nunique().gt(1).sum())
        report["duplicate_feature_groups_with_mixed_labels"] = mixed
    groups = [c for c in group_candidates if c in df.columns]
    report["available_group_columns"] = groups
    return report


def experiment_e8(run_model_generalisation: bool = True) -> Dict[str, Any]:
    """E8: smashed-activation leakage, integrity audit and generalisation.

    NSL-KDD is available automatically.  Other datasets are audited when their
    paths are supplied.  UNSW-NB15 can also enter model generalisation when its
    predefined train/test CSV paths are configured.  CIC/TON formats vary; this
    function deliberately refuses to guess a label/group protocol silently.
    """
    out = exp_dir("E8_IDS_integrity_generalisation")
    nsl_data = load_nsl_kdd(CFG.seed)
    reports: Dict[str, Any] = {"NSL_KDD": nsl_data.audit}
    leakage = run_activation_leakage_audit(nsl_data)
    leakage.to_csv(out / "E8_smashed_activation_leakage_by_cut.csv", index=False)
    summarize_numeric(leakage, ["cut"], ["reconstruction_mse_standardised", "reconstruction_r2",
                                         "label_inference_auc", "label_inference_f1"]).to_csv(
        out / "E8_smashed_activation_leakage_summary_mean_ci.csv", index=False)
    paths = {
        "UNSW_train": CFG.unsw_train_csv, "UNSW_test": CFG.unsw_test_csv,
        "CICIDS2017": CFG.cicids2017_csv, "CICDDoS2019": CFG.cicddos2019_csv,
    }
    for name, path in paths.items():
        if path and Path(path).exists():
            reports[name] = audit_csv(path)
    if CFG.ton_iot_dir and Path(CFG.ton_iot_dir).exists():
        reports["TON_IoT"] = {p.name: audit_csv(str(p)) for p in sorted(Path(CFG.ton_iot_dir).glob("*.csv"))}
    save_json(out / "E8_integrity_audit.json", reports)
    generalisation_rows = []
    if run_model_generalisation:
        dataset_names = ["NSL_KDD"]
        if CFG.unsw_train_csv and CFG.unsw_test_csv: dataset_names.append("UNSW_NB15")
        for dataset_name in dataset_names:
            data = load_dataset(dataset_name, CFG.seed)
            for arch in ("deep_mlp", "residual_mlp"):
                for seed in CFG.generalisation_seeds:
                    oracle = create_or_load_oracle(data, arch, 20, seed)
                    chosen = oracle[oracle.eligible] if oracle.eligible.any() else oracle
                    row = chosen.sort_values("reward", ascending=False).iloc[0].to_dict()
                    selected_cut = int(row["cut"])
                    # The selected cut is retrained with the larger final budget.
                    # Test labels are touched only here, after validation-only selection.
                    final_run = train_candidate(
                        data, arch, 20, selected_cut, seed,
                        epochs=CFG.final_epochs, initial_state=None, return_state=True,
                    )
                    row.update({f"test_{k}": v for k, v in final_run["test_metrics"].items()})
                    row["final_train_seconds"] = final_run["train_seconds"]
                    row.update({"dataset": dataset_name, "architecture": arch, "seed": seed})
                    generalisation_rows.append(row)
        if generalisation_rows:
            gen = pd.DataFrame(generalisation_rows)
            gen.to_csv(out / "E8_cross_dataset_selected_splits.csv", index=False)
            summarize_numeric(gen, ["dataset", "architecture"],
                              ["cut", "val_f1", "val_recall", "val_pr_auc", "reward",
                               "test_f1", "test_recall", "test_pr_auc", "test_roc_auc"]).to_csv(
                out / "E8_cross_dataset_summary_mean_ci.csv", index=False)
    print("E8 complete:", out)
    return {"leakage": leakage, "audit": reports, "generalisation": pd.DataFrame(generalisation_rows)}



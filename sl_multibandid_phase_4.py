class DeepMLP(nn.Module):
    def __init__(self, input_dim):
        super().__init__()
        dims=[input_dim,128,128,128,120,120,120]
        self.blocks=nn.ModuleList([nn.Sequential(nn.Linear(dims[i],dims[i+1]),nn.ReLU()) for i in range(6)])
        self.head=nn.Linear(dims[-1],1)
    def forward(self,x,cut=None):
        for block in self.blocks: x=block(x)
        return self.head(x).squeeze(1)

def loader(X,y,shuffle,seed):
    g=torch.Generator().manual_seed(seed)
    return DataLoader(TensorDataset(torch.from_numpy(X),torch.from_numpy(np.asarray(y,dtype=np.float32))),
                      batch_size=BATCH_SIZE,shuffle=shuffle,generator=g)

def evaluate(model,X,y):
    model.eval(); scores=[]
    with torch.no_grad():
        for xb,_ in loader(X,y,False,0): scores.extend(torch.sigmoid(model(xb.to(DEVICE))).cpu().numpy())
    scores=np.asarray(scores); pred=(scores>=0.5).astype(int); yt=np.asarray(y).astype(int)
    return {'val_precision':precision_score(yt,pred,zero_division=0),'val_recall':recall_score(yt,pred,zero_division=0),
            'val_f1':f1_score(yt,pred,zero_division=0),'val_roc_auc':roc_auc_score(yt,scores),
            'val_pr_auc':average_precision_score(yt,scores)}

def train_fresh(seed,epochs=2):
    torch.manual_seed(seed); np.random.seed(seed)
    model=DeepMLP(INPUT_DIM).to(DEVICE); opt=torch.optim.Adam(model.parameters(),lr=1e-3); lossfn=nn.BCEWithLogitsLoss()
    t0=time.perf_counter(); model.train()
    for _ in range(epochs):
        for xb,yb in loader(X_train,y_train,True,seed):
            xb,yb=xb.to(DEVICE),yb.to(DEVICE); opt.zero_grad(); loss=lossfn(model(xb),yb); loss.backward(); opt.step()
    metrics=evaluate(model,X_val,y_val); metrics['train_seconds']=time.perf_counter()-t0
    return model,metrics

def fresh_profiles(seeds=(0,1,2,3,4),epochs=2):
    rows=[]
    for seed in seeds:
        model,met=train_fresh(seed,epochs)
        dims=[128,128,128,120,120,120]
        linears=[m[0] for m in model.blocks]
        for cut in range(1,7):
            activation=dims[cut-1]; comm_bytes=2*BATCH_SIZE*activation*4
            client_flops=sum(2*m.in_features*m.out_features for m in linears[:cut])
            server_flops=sum(2*m.in_features*m.out_features for m in linears[cut:])+2*dims[-1]
            client_params=sum(p.numel() for b in model.blocks[:cut] for p in b.parameters())
            memory_mb=(client_params*4 + BATCH_SIZE*activation*4)/(1024**2)
            client_mflops=client_flops*BATCH_SIZE/1e6; server_mflops=server_flops*BATCH_SIZE/1e6
            comm_mb=comm_bytes/1e6; comm_ms=comm_mb*8*1000/25.0
            latency=comm_ms+client_mflops/1.0+server_mflops/10.0
            rows.append({'seed':seed,'cut':cut,**met,'activation_elements_per_sample':activation,
                'communication_bytes_batch':comm_bytes,'communication_mb_batch':comm_mb,
                'client_mflops_batch':client_mflops,'server_mflops_batch':server_mflops,
                'client_memory_mb':memory_mb,'estimated_total_latency_ms':latency})
    d=pd.DataFrame(rows)
    for seed,g in d.groupby('seed'):
        idx=g.index
        def norm(s):
            lo,hi=s.min(),s.max(); return (s-lo)/(hi-lo) if hi>lo else s*0
        d.loc[idx,'norm_comm']=norm(g.communication_mb_batch)
        d.loc[idx,'norm_client']=norm(g.client_mflops_batch)
        d.loc[idx,'norm_latency']=norm(g.estimated_total_latency_ms)
    d['feasible']=(d.client_memory_mb<=1.6)&(d.estimated_total_latency_ms<=250.0)
    d['reward']=d.val_f1-0.25*d.norm_comm-0.15*d.norm_client-0.10*d.norm_latency
    return d


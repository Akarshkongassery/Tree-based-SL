# ## Experiment E10 — Non-stationary selection with hard feasibility
#
# This experiment recomputes feasibility before every decision. An infeasible
# cut is never passed to a policy. Regret is measured against the best currently
# feasible cut. Replace the budgets below with the paper's deployed limits.

# %%
#@title E10. Run step, recovery, and oscillating schedules
E10_OUT = reset_output('E10_nonstationary_feasible')
E10_METHODS = ['random_feasible', 'sliding_ucb', 'discounted_ucb']
SCHEDULES = {
    'step': [(1,20,50.0,1.0),(21,40,5.0,1.0),(41,60,10.0,0.35)],
    'recovery': [(1,15,25.0,0.8),(16,30,3.0,0.8),(31,45,3.0,0.3),(46,60,50.0,1.0)],
    'oscillating': [(1,10,50.0,1.0),(11,20,5.0,0.4),(21,30,50.0,1.0),
                    (31,40,5.0,0.4),(41,50,50.0,1.0),(51,60,5.0,0.4)],
}
MAX_MEMORY_MB = 1.6
MAX_LATENCY_MS = 500.0
GAMMA = 0.90
WINDOW = 10

def context_at(blocks, t):
    for lo, hi, bw, gf in blocks:
        if lo <= t <= hi:
            return bw, gf
    raise ValueError(t)

def contextual_table(d, bandwidth, client_gflops):
    x = d.copy()
    x['ctx_comm_ms'] = x.communication_mb_batch*8*1000/bandwidth
    x['ctx_client_ms'] = x.client_mflops_batch/client_gflops
    server_ms = x.get('server_mflops_batch', pd.Series(0.0,index=x.index))/10.0
    x['ctx_latency_ms'] = x.ctx_comm_ms + x.ctx_client_ms + server_ms
    x['ctx_feasible'] = (x.client_memory_mb <= MAX_MEMORY_MB) & (x.ctx_latency_ms <= MAX_LATENCY_MS)
    def mm(s):
        lo, hi = float(s.min()), float(s.max())
        return (s-lo)/(hi-lo) if hi > lo else pd.Series(0.0,index=s.index)
    x['ctx_reward'] = x.val_f1 - 0.25*mm(x.communication_mb_batch) - 0.15*mm(x.client_mflops_batch) - 0.10*mm(x.ctx_latency_ms)
    return x

online_rows = []
for seed in SEEDS:
    base = seed_profiles(seed)
    for schedule, blocks in SCHEDULES.items():
        for method in E10_METHODS:
            rng = np.random.default_rng(seed*100 + E10_METHODS.index(method))
            rewards = {int(c): [] for c in base.cut}
            disc_sum = {int(c): 0.0 for c in base.cut}
            disc_n = {int(c): 0.0 for c in base.cut}
            for t in range(1,61):
                bw, gf = context_at(blocks,t)
                ctx = contextual_table(base,bw,gf)
                feasible = ctx[ctx.ctx_feasible].copy()
                if feasible.empty:
                    online_rows.append({'seed':seed,'schedule':schedule,'method':method,'round':t,
                        'bandwidth_mbps':bw,'client_gflops':gf,'selected_cut':np.nan,
                        'reward':np.nan,'instant_regret':np.nan,'feasible':0,'optimal_now':0,'no_feasible_arm':1})
                    continue
                truth = dict(zip(feasible.cut.astype(int),feasible.ctx_reward.astype(float)))
                optimum = max(truth,key=truth.get)
                arms = list(truth)
                if method == 'random_feasible':
                    cut = int(rng.choice(arms))
                elif method == 'sliding_ucb':
                    score = {}
                    for c in arms:
                        recent = rewards[c][-WINDOW:]
                        score[c] = (np.mean(recent) + 0.20*math.sqrt(math.log(t+1)/len(recent))) if recent else 1.0
                    cut = int(max(score,key=score.get))
                else:
                    score = {c: (disc_sum[c]/disc_n[c] + 0.20*math.sqrt(math.log(t+1)/disc_n[c])) if disc_n[c] else 1.0 for c in arms}
                    cut = int(max(score,key=score.get))
                y = observe(truth[cut],rng)
                rewards[cut].append(y)
                for c in disc_sum:
                    disc_sum[c] *= GAMMA; disc_n[c] *= GAMMA
                disc_sum[cut] += y; disc_n[cut] += 1
                online_rows.append({'seed':seed,'schedule':schedule,'method':method,'round':t,
                    'bandwidth_mbps':bw,'client_gflops':gf,'selected_cut':cut,'reward':truth[cut],
                    'instant_regret':truth[optimum]-truth[cut],'feasible':1,
                    'optimal_now':int(cut==optimum),'optimal_cut':optimum,'no_feasible_arm':0})

e10 = pd.DataFrame(online_rows)
e10_seed = e10.groupby(['seed','schedule','method'],as_index=False).agg(
    cumulative_regret=('instant_regret','sum'), mean_reward=('reward','mean'),
    feasible_rate=('feasible','mean'), optimal_rate=('optimal_now','mean'),
    no_feasible_rounds=('no_feasible_arm','sum'))
e10_summary = e10_seed.groupby(['schedule','method']).agg(
    cumulative_regret_mean=('cumulative_regret','mean'), cumulative_regret_sd=('cumulative_regret','std'),
    mean_reward=('mean_reward','mean'), feasible_rate=('feasible_rate','mean'),
    optimal_rate=('optimal_rate','mean'), no_feasible_rounds=('no_feasible_rounds','mean')).reset_index()
e10.to_csv(E10_OUT/'E10_online_histories.csv',index=False)
e10_seed.to_csv(E10_OUT/'E10_seed_level.csv',index=False)
e10_summary.to_csv(E10_OUT/'E10_summary.csv',index=False)
print(e10_summary.to_string(index=False))

